import "server-only";

import { redirect } from "next/navigation";
import type { User } from "@supabase/supabase-js";
import { createClient } from "@/lib/supabase/server";

/**
 * Ensures the current request is from a signed-in admin. Returns the user, or
 * redirects to the login page. Use at the top of admin Server Components and
 * Server Actions as defense-in-depth alongside the middleware gate.
 */
export async function requireUser(): Promise<User> {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    redirect("/admin/login");
  }

  return user;
}
